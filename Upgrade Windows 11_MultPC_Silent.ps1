foreach ($computer in $computers) {
    Write-Host "Starting Windows 11 upgrade process on $computer"
    
    try {
        # Check if remote computer is accessible
        if (Test-Connection -ComputerName $computer -Count 1 -Quiet) {
            # Create remote session
            $session = New-PSSession -ComputerName $computer
            
            Invoke-Command -Session $session -ScriptBlock {
                # Enable Windows Update service
                Set-Service -Name wuauserv -StartupType Automatic
                Start-Service -Name wuauserv
                
                # Install Windows Update PowerShell module if not present
                if (!(Get-Module -ListAvailable -Name PSWindowsUpdate)) {
                    Install-Module -Name PSWindowsUpdate -Force
                }
                
                # Import the module
                Import-Module PSWindowsUpdate
                
                # Start Windows 11 upgrade
                Get-WindowsUpdate -AcceptAll -Install -IgnoreReboot
            }
            
            Write-Host "Update process initiated on $computer"
            Remove-PSSession $session
            
        } else {
            Write-Warning "Cannot connect to $computer"
        }
    }
    catch {
        Write-Error "Error occurred while processing $computer : $_"
    }
}